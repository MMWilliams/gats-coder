"""Export the speaker script from the main slides' notes to talk/SCRIPT.md.

    python script.py    # also runs at the end of build.py

The notes in index.html are the source; edit them, not SCRIPT.md.
[Brackets] are stage directions and don't count toward spoken time.
"""
import html
import re
from pathlib import Path

HERE = Path(__file__).parent
WPM = 140  # conversational talk pace


def seconds(t):
    m, s = t.split(":")
    return int(m) * 60 + int(s)


def clock(sec):
    return f"{int(sec) // 60}:{int(sec) % 60:02d}"


def text(fragment):
    return " ".join(html.unescape(re.sub(r"<[^>]+>", " ", fragment)).split())


def export():
    deck = (HERE / "index.html").read_text(encoding="utf-8")
    slides = re.findall(r'<section data-t="([^"]+)"[^>]*>(.*?)</section>', deck, re.S)
    out, total, over = [], 0.0, []
    for i, (start, body) in enumerate(slides):
        end = slides[i + 1][0] if i + 1 < len(slides) else None
        heading = re.search(r"<h[12][^>]*>(.*?)</h[12]>", body, re.S) or re.search(r'class="eyebrow">(.*?)</div>', body, re.S)
        title = text(heading.group(1))
        notes = text(re.search(r'<aside class="notes">(.*?)</aside>', body, re.S).group(1))
        notes = re.sub(r"^\d+:\d\d-(\d+:\d\d)?\.\s*", "", notes)
        words = len(re.sub(r"\[[^\]]*\]", "", notes).split())
        spoken = words / WPM * 60
        total += spoken
        slot = seconds(end) - seconds(start) if end else None
        timing = f"{start}-{end or ''} · {words} words · ~{clock(spoken)}"
        if slot:
            timing += f" of {clock(slot)}"
            if spoken > slot:
                timing += " · OVER"
                over.append(i + 1)
        out += [f"## {i + 1}. {title}", "", f"_{timing}_", "", notes, ""]
    head = ["# Speaker script: What did your agent actually do?", "",
            "Generated by deck/script.py from the speaker notes in deck/index.html. Edit the notes, then run "
            f"build.py or script.py. [Brackets] are stage directions. Times assume {WPM} words per minute.", "",
            f"Spoken total: ~{clock(total)} for {len(slides)} slides." + (f" Over time: slides {over}." if over else ""), ""]
    (HERE.parent / "SCRIPT.md").write_text("\n".join(head + out), encoding="utf-8")
    print(f"script: ~{clock(total)} spoken" + (f", over on {over}" if over else ""))


if __name__ == "__main__":
    export()
